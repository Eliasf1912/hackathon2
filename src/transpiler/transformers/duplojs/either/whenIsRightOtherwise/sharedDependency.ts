import * as DCommon from "@duplojs/lang/common";
import * as DArray from "@duplojs/lang/array";
import { GoAST } from "@go";
import { createSharedDependency } from "@transformer";

export const whenIsRightOtherwiseFunctionIdentifier = GoAST.createIdentifier("EitherWhenIsRightOtherwise");
export const whenIsRightOtherwiseWithFunctionIdentifier = GoAST.createIdentifier("EitherWhenIsRightOtherwiseWith");

const valueGeneric = GoAST.createIdentifier("V");
const otherwiseGeneric = GoAST.createIdentifier("L");
const outputGeneric = GoAST.createIdentifier("O");
const input = GoAST.createIdentifier("input");
const theFunction = GoAST.createIdentifier("theFunction");
const otherwiseFunction = GoAST.createIdentifier("otherwiseFunction");
const isRight = GoAST.createIdentifier("isRight");
const rightValue = GoAST.createIdentifier("rightValue");

const typeParameters = DArray.map(
	[valueGeneric, otherwiseGeneric, outputGeneric],
	(identifier) => GoAST.createTypeParameter({
		identifier,
		constraint: GoAST.builtinTypeReferences.any,
	}),
);

const inputArgument = GoAST.createFunctionArgument({
	identifier: input,
	type: GoAST.builtinTypeReferences.any,
});

const callbackArguments = [
	GoAST.createFunctionArgument({
		identifier: theFunction,
		type: GoAST.createFunctionType({
			arguments: [
				GoAST.createFunctionArgument({
					identifier: GoAST.createIdentifier("value"),
					type: valueGeneric,
				}),
			],
			returnTypes: [outputGeneric],
		}),
	}),
	GoAST.createFunctionArgument({
		identifier: otherwiseFunction,
		type: GoAST.createFunctionType({
			arguments: [
				GoAST.createFunctionArgument({
					identifier: GoAST.createIdentifier("value"),
					type: otherwiseGeneric,
				}),
			],
			returnTypes: [outputGeneric],
		}),
	}),
];

/**
 * The checks generated by the handler from the Either variants of the input:
 * `isRight` tells whether the input is a Right, `rightValue` reads its value.
 */
const checkArguments = [
	GoAST.createFunctionArgument({
		identifier: isRight,
		type: GoAST.createFunctionType({
			arguments: [inputArgument],
			returnTypes: [GoAST.builtinTypeReferences.bool],
		}),
	}),
	GoAST.createFunctionArgument({
		identifier: rightValue,
		type: GoAST.createFunctionType({
			arguments: [inputArgument],
			returnTypes: [valueGeneric],
		}),
	}),
];

const curriedResultType = GoAST.createFunctionType({
	arguments: [inputArgument],
	returnTypes: [outputGeneric],
});

/**
 * `EitherWhenIsRightOtherwise[V, L, O](isRight, rightValue)(input, theFunction, otherwiseFunction)`.
 */
const delegateToDirectForm = GoAST.createCallExpression({
	callee: GoAST.createCallExpression({
		callee: GoAST.createInstantiationExpression({
			target: whenIsRightOtherwiseFunctionIdentifier,
			typeArguments: DCommon.cast([valueGeneric, otherwiseGeneric, outputGeneric]),
		}),
		arguments: [isRight, rightValue],
	}),
	arguments: [input, theFunction, otherwiseFunction],
});

/**
 * Mirrors `DEither.whenIsRightOtherwise`: the value of a Right goes to
 * `theFunction`, any other input goes as is to `otherwiseFunction`, converted
 * to the type proven by TypeScript.
 */
export const eitherWhenIsRightOtherwiseDependency = DCommon.memo(
	() => createSharedDependency({
		imports: [],
		init: [],
		declarations: [
			GoAST.createFunctionDeclaration({
				identifier: whenIsRightOtherwiseFunctionIdentifier,
				generic: typeParameters,
				arguments: checkArguments,
				returnTypes: [
					GoAST.createFunctionType({
						arguments: DArray.concat([inputArgument], callbackArguments),
						returnTypes: [outputGeneric],
					}),
				],
				body: GoAST.createBlockStatement({
					statements: [
						GoAST.createReturnStatement({
							values: [
								GoAST.createFunctionLiteral({
									arguments: DArray.concat([inputArgument], callbackArguments),
									returnTypes: [outputGeneric],
									body: GoAST.createBlockStatement({
										statements: [
											GoAST.createIfStatement({
												condition: GoAST.createCallExpression({
													callee: isRight,
													arguments: [input],
												}),
												body: GoAST.createBlockStatement({
													statements: [
														GoAST.createReturnStatement({
															values: [
																GoAST.createCallExpression({
																	callee: theFunction,
																	arguments: [
																		GoAST.createCallExpression({
																			callee: rightValue,
																			arguments: [input],
																		}),
																	],
																}),
															],
														}),
													],
												}),
											}),
											GoAST.createReturnStatement({
												values: [
													GoAST.createCallExpression({
														callee: otherwiseFunction,
														arguments: [
															GoAST.createTypeAssertionExpression({
																target: input,
																typeReference: otherwiseGeneric,
															}),
														],
													}),
												],
											}),
										],
									}),
								}),
							],
						}),
					],
				}),
			}),
		],
	}),
);

/**
 * Curried form `DEither.whenIsRightOtherwise(theFunction, otherwiseFunction)`.
 * Requires the `EitherWhenIsRightOtherwise` dependency.
 */
export const eitherWhenIsRightOtherwiseWithDependency = DCommon.memo(
	() => createSharedDependency({
		imports: [],
		init: [],
		declarations: [
			GoAST.createFunctionDeclaration({
				identifier: whenIsRightOtherwiseWithFunctionIdentifier,
				generic: typeParameters,
				arguments: checkArguments,
				returnTypes: [
					GoAST.createFunctionType({
						arguments: callbackArguments,
						returnTypes: [curriedResultType],
					}),
				],
				body: GoAST.createBlockStatement({
					statements: [
						GoAST.createReturnStatement({
							values: [
								GoAST.createFunctionLiteral({
									arguments: callbackArguments,
									returnTypes: [curriedResultType],
									body: GoAST.createBlockStatement({
										statements: [
											GoAST.createReturnStatement({
												values: [
													GoAST.createFunctionLiteral({
														arguments: [inputArgument],
														returnTypes: [outputGeneric],
														body: GoAST.createBlockStatement({
															statements: [
																GoAST.createReturnStatement({
																	values: [delegateToDirectForm],
																}),
															],
														}),
													}),
												],
											}),
										],
									}),
								}),
							],
						}),
					],
				}),
			}),
		],
	}),
);
