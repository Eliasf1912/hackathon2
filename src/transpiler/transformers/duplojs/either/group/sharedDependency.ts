import * as DCommon from "@duplojs/lang/common";
import * as DArray from "@duplojs/lang/array";
import { GoAST } from "@go";
import { createSharedDependency } from "@transformer";
import { successFunctionIdentifier } from "../success/sharedDependency";

export const groupFunctionIdentifier = GoAST.createIdentifier("EitherGroup");
export const groupOfGettersFunctionIdentifier = GoAST.createIdentifier("EitherGroupOfGetters");

/**
 * Mirrors `DEither.group` on an array: collects the values of the Rights in
 * order and stops at the first other result, returned unchanged with its
 * information. When every result is a Right, the values form a success.
 *
 * With getters (`[() => result]`), each getter is only called once the
 * previous results are Rights, like `DEither.asyncGroup` awaits them in turn.
 * `isRight` and `rightValue` are generated by the handler from the variants.
 */
function createGroupFunction(
	identifier: GoAST.Identifier,
	withGetters: boolean,
) {
	const elementGeneric = GoAST.createIdentifier("E");
	const valueGeneric = GoAST.createIdentifier("V");
	const group = GoAST.createIdentifier("group");
	const values = GoAST.createIdentifier("values");
	const item = GoAST.createIdentifier("item");
	const element = GoAST.createIdentifier("element");
	const isRight = GoAST.createIdentifier("isRight");
	const rightValue = GoAST.createIdentifier("rightValue");
	const valuesType = GoAST.createSliceType({ elementType: valueGeneric });
	const returnElement = GoAST.createBlockStatement({
		statements: [GoAST.createReturnStatement({ values: [element] })],
	});
	const inputArgument = GoAST.createFunctionArgument({
		identifier: GoAST.createIdentifier("input"),
		type: GoAST.builtinTypeReferences.any,
	});
	const groupArgument = GoAST.createFunctionArgument({
		identifier: group,
		type: GoAST.createSliceType({
			elementType: withGetters
				? GoAST.createFunctionType({
					arguments: [],
					returnTypes: [elementGeneric],
				})
				: elementGeneric,
		}),
	});

	return GoAST.createFunctionDeclaration({
		identifier,
		generic: DArray.map(
			[elementGeneric, valueGeneric],
			(typeIdentifier) => GoAST.createTypeParameter({
				identifier: typeIdentifier,
				constraint: GoAST.builtinTypeReferences.any,
			}),
		),
		arguments: [
			GoAST.createFunctionArgument({
				identifier: isRight,
				type: GoAST.createFunctionType({
					arguments: [inputArgument],
					returnTypes: [GoAST.builtinTypeReferences.bool],
				}),
			}),
			GoAST.createFunctionArgument({
				identifier: rightValue,
				type: GoAST.createFunctionType({
					arguments: [inputArgument],
					returnTypes: [valueGeneric],
				}),
			}),
		],
		returnTypes: [
			GoAST.createFunctionType({
				arguments: [groupArgument],
				returnTypes: [GoAST.builtinTypeReferences.any],
			}),
		],
		body: GoAST.createBlockStatement({
			statements: [
				GoAST.createReturnStatement({
					values: [
						GoAST.createFunctionLiteral({
							arguments: [groupArgument],
							returnTypes: [GoAST.builtinTypeReferences.any],
							body: GoAST.createBlockStatement({
								statements: [
									GoAST.createShortVariableDeclarationStatement({
										identifier: values,
										initializer: GoAST.createCallExpression({
											callee: GoAST.createIdentifier("make"),
											typeArgument: valuesType,
											arguments: [
												GoAST.createIntegerLiteral({ value: 0n }),
												GoAST.createCallExpression({
													callee: GoAST.createIdentifier("len"),
													arguments: [group],
												}),
											],
										}),
									}),
									GoAST.createRangeStatement({
										binding: GoAST.createRangeDeclaration({
											key: GoAST.createIdentifier("_"),
											value: item,
										}),
										expression: group,
										body: GoAST.createBlockStatement({
											statements: [
												GoAST.createShortVariableDeclarationStatement({
													identifier: element,
													initializer: withGetters
														? GoAST.createCallExpression({
															callee: item,
															arguments: [],
														})
														: item,
												}),
												GoAST.createIfStatement({
													condition: GoAST.createUnaryExpression({
														operator: "!",
														operand: GoAST.createCallExpression({
															callee: isRight,
															arguments: [element],
														}),
													}),
													body: returnElement,
												}),
												GoAST.createAssignmentStatement({
													targets: DCommon.cast([values]),
													values: DCommon.cast([
														GoAST.createCallExpression({
															callee: GoAST.createIdentifier("append"),
															arguments: [
																values,
																GoAST.createCallExpression({
																	callee: rightValue,
																	arguments: [element],
																}),
															],
														}),
													]),
												}),
											],
										}),
									}),
									GoAST.createReturnStatement({
										values: [
											GoAST.createCallExpression({
												callee: GoAST.createInstantiationExpression({
													target: successFunctionIdentifier,
													typeArguments: DCommon.cast([valuesType]),
												}),
												arguments: [values],
											}),
										],
									}),
								],
							}),
						}),
					],
				}),
			],
		}),
	});
}

/**
 * Requires the success dependency.
 */
export const eitherGroupDependency = DCommon.memo(
	() => createSharedDependency({
		imports: [],
		init: [],
		declarations: [createGroupFunction(groupFunctionIdentifier, false)],
	}),
);

/**
 * Requires the success dependency.
 */
export const eitherGroupOfGettersDependency = DCommon.memo(
	() => createSharedDependency({
		imports: [],
		init: [],
		declarations: [createGroupFunction(groupOfGettersFunctionIdentifier, true)],
	}),
);
